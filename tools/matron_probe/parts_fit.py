#!/usr/bin/env python3
"""Her body's parts for blows (J-060), from her drawn limb volumes.

Reads tests/data/matron_drawn_limbs.inc (shape_fit.py --fixture: each bone of
her rig as a segment with the radius of her flesh about it, in her body frame,
for 30 recorded frames of each stance family) and writes, per stance, the
median of each segment's ends and radius over its frames: one pose per stance,
the parts her simulation strikes (src/sim/matron_parts.inc).

    python3 tools/matron_probe/parts_fit.py [fixture.inc] [out.inc]
"""
import os
import re
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROW = re.compile(r"\{(\d+), (\d+), (\d+), \{([^}]*)\}, \{([^}]*)\}, ([-\d.]+)F\}")


def vec(text):
    return [float(x.strip().rstrip("F")) for x in text.split(",")]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tests/data/matron_drawn_limbs.inc")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "src/sim/matron_parts.inc")
    frames = {}
    for line in open(src):
        m = ROW.match(line.strip())
        if m:
            frames.setdefault((int(m[1]), int(m[2])), []).append((int(m[3]), vec(m[4]), vec(m[5]), float(m[6])))
    with open(out, "w") as fh:
        fh.write("// Generated by tools/matron_probe/parts_fit.py from tests/data/matron_drawn_limbs.inc:\n")
        fh.write("// per stance, the median over its recorded frames of each drawn limb segment (body\n")
        fh.write("// frame: x right, y up, z forward, about her simulated middle): stance, region, a, b,\n")
        fh.write("// radius. Region 0 trunk and head, 1 forearm and hand, 2 upper arm, 3 leg.\n")
        fh.write("// Do not edit by hand.\n")
        for stance in sorted({s for s, _ in frames}):
            fs = [frames[k] for k in sorted(frames) if k[0] == stance]
            for i in range(len(fs[0])):
                a = [statistics.median(f[i][1][c] for f in fs) for c in range(3)]
                b = [statistics.median(f[i][2][c] for f in fs) for c in range(3)]
                r = statistics.median(f[i][3] for f in fs)
                fh.write("{%d, %d, {%.3fF, %.3fF, %.3fF}, {%.3fF, %.3fF, %.3fF}, %.3fF},\n" % (
                    stance, fs[0][i][0], a[0], a[1], a[2], b[0], b[1], b[2], r))


if __name__ == "__main__":
    main()
