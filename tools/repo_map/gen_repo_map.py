#!/usr/bin/env python3
"""Regenerate REPO_MAP.md: key files, key functions with line numbers, test groups.

Run from the repository root:  python3 tools/repo_map/gen_repo_map.py
Reads only; writes REPO_MAP.md. Line numbers are for the commit it ran on (printed at the top).
"""
import pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
# Files whose functions are listed one by one (the ones agents keep searching for).
KEY_FUNC_GLOBS = ["src/sim/matron*.cpp", "src/sim/matron*.hpp", "src/sim/physics_world*.cpp",
                  "src/sim/simulation.cpp", "src/sim/mechanism_kit.cpp"]
FUNC_RE = re.compile(r"^(?!#|//|/\*|\s|\}|\{|return\b|if\b|for\b|while\b|switch\b|else\b)"
                     r"[^;=]*?\b([A-Za-z_]\w*(?:::~?\w+)*)\s*\(")
SKIP_NAMES = {"if", "for", "while", "switch", "return", "sizeof", "static_assert", "TEST", "namespace"}
TYPE_RE = re.compile(r"^\s*(struct|class|enum class|enum)\s+(\w+)")
LIMIT_RE = re.compile(r"\b(Limits|Budget|total_force_n|budget)\b")


def sh(*a):
    return subprocess.check_output(a, cwd=ROOT, text=True).strip()


def rel(p):
    return p.relative_to(ROOT).as_posix()


def functions(path):
    out, lines = [], path.read_text(errors="replace").splitlines()
    for i, line in enumerate(lines, 1):
        m = FUNC_RE.match(line)
        if not m or line.rstrip().endswith(";"):
            continue
        name = m.group(1)
        if name.split("::")[-1] in SKIP_NAMES:
            continue
        # a definition: '{' on this line or within the next three
        tail = " ".join(lines[i - 1:i + 3])
        if "{" in tail and ";" not in line:
            out.append((i, name))
    return out


def main():
    sha = sh("git", "rev-parse", "--short", "HEAD")
    o = [f"# ScraperX repository map",
         "",
         f"Generated by `tools/repo_map/gen_repo_map.py` at `{sha}`. Do not edit by hand: rerun it.",
         "Line numbers drift as files change; search the name if a line is off.",
         "Rules: `CLAUDE.md` / `AGENTS.md`. Authority and owner directives: `00_START_HERE.md`.",
         "", "## Layout", "",
         "| Path | What |", "|---|---|",
         "| `src/sim/` | native C++17 / Jolt simulation at 90 Hz; owns every consequential fact |",
         "| `src/bridge/` | Godot GDExtension bridge |",
         "| `tests/` | native tests: one executable, groups picked with `SCRAPERX_ONLY=<group>` |",
         "| `godot/` | presentation, input, HUD, touch scenarios (`--uitest`), Android export |",
         "| `.github/workflows/wo000-delivery-spine.yml` | the proof run (CI) and the APKs |",
         "| `03_EXECUTION/` | tickets, plans, designs; `handoffs/TEMPLATE.yml`, `REVIEW_CHECKLIST.md` |",
         "| `tools/rule_check/` | rule check over a diff (see `CLAUDE.md`) |",
         "", "## Largest source files", "", "| File | Lines |", "|---|---|"]
    srcs = sorted((p for p in (ROOT / "src").rglob("*") if p.suffix in (".cpp", ".hpp", ".h")),
                  key=lambda p: -sum(1 for _ in p.open(errors="replace")))
    for p in srcs[:25]:
        o.append(f"| `{rel(p)}` | {sum(1 for _ in p.open(errors='replace'))} |")

    o += ["", "## Her force limits and budget (where to look; changing them needs a PR)", ""]
    for p in sorted((ROOT / "src/sim").glob("matron*.hpp")):
        for i, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            if TYPE_RE.match(line) and LIMIT_RE.search(line):
                o.append(f"- `{rel(p)}:{i}` {line.strip()[:100]}")
            elif re.search(r"total_force_n|8000\.5|9800|65000|65 kW|220\.0", line):
                o.append(f"- `{rel(p)}:{i}` `{line.strip()[:100]}`")

    o += ["", "## Key functions", ""]
    files = sorted({p for g in KEY_FUNC_GLOBS for p in ROOT.glob(g)})
    for p in files:
        fs = functions(p)
        if not fs:
            continue
        o.append(f"**`{rel(p)}`**: " + ", ".join(f"`{n}` {i}" for i, n in fs))
        o.append("")

    sim = (ROOT / "tests/simulation_tests.cpp").read_text(errors="replace")
    groups = sorted(set(re.findall(r'std::string\(only\)\s*==\s*"([^"]+)"', sim)))
    cm = (ROOT / "CMakeLists.txt").read_text()
    m = re.search(r"foreach\(slice ([^)]*)\)", cm)
    slices = m.group(1).split() if m else []
    knobs = set()
    for p in list((ROOT / "tests").glob("*.cpp")) + list((ROOT / "src").rglob("*.cpp")):
        knobs |= set(re.findall(r'getenv\("(SCRAPERX_[A-Z_]+)"\)', p.read_text(errors="replace")))
    knobs.discard("SCRAPERX_ONLY")
    touch = set()
    for p in (ROOT / "godot").rglob("*.gd"):
        touch |= set(re.findall(r'"(touch_[a-z0-9_]+)"', p.read_text(errors="replace")))
    o += ["## Test groups", "",
          f"**Native, `SCRAPERX_ONLY=<group> ./build/host/scraperx_sim_tests`** ({len(groups)}): "
          + ", ".join(f"`{g}`" for g in groups), "",
          f"**Also their own ctest entries** (CI runs them as slices): " + ", ".join(f"`{s}`" for s in slices), "",
          f"**Debug and trace knobs (env)**: " + ", ".join(f"`{k}`" for k in sorted(knobs)), "",
          f"**Touch scenarios** (`--uitest`, {len(touch)}): " + ", ".join(f"`{t}`" for t in sorted(touch)), ""]
    (ROOT / "REPO_MAP.md").write_text("\n".join(o) + "\n")
    print(f"REPO_MAP.md written at {sha}: {len(files)} key files, {len(groups)} groups, {len(touch)} touch scenarios")


if __name__ == "__main__":
    main()
