class CodexCommand(unittest.TestCase):
    """A comment that starts `@codex` is a command to Codex, nobody's post: the switchboard posts `@codex review`
    under the team login, and the integrator types it by hand. Unsigned it read as ChatGPT's, with the footer as
    Claude's, so it could pass for their answer to an open ask on that PR's thread (a false ack)."""
    SHA = "1a2b3c4d" * 5
    BOT_SHAPE = f"@codex review\n\n<!-- switchboard:ask-codex pr=377 head={SHA} -->"
    HAND = "@codex review"
    HAND_FOOT = "  @Codex review" + FOOT

    def test_it_is_nobodys_post(self):
        for body in (self.BOT_SHAPE, self.HAND, self.HAND_FOOT, "\n\n@CODEX review this head, please"):
            self.assertEqual(asks.author(body), "noise", body)
        self.assertEqual(asks.author("Claude (integrator): I posted @codex review on #377." + FOOT), "Claude")

    def test_it_never_answers_an_ask_and_is_never_an_ask(self):
        for asker, target, ask in (("Claude", "ChatGPT", "To ChatGPT: second read wanted on this head." + FOOT),
                                   ("ChatGPT", "Claude", "To Claude (from ChatGPT): which head do I review?")):
            for body in (self.BOT_SHAPE, self.HAND, self.HAND_FOOT, self.HAND + "\n\ncc " + asker):
                stream = [c(7001, 377, at(9, "10:00"), ask), c(7002, 377, at(9, "10:05"), body)]
                got = asks.read(stream, {377}, at(7, "00:00"), job_threads={377}, who=who)
                self.assertEqual([(a["id"], a["target"], a["answer"]) for a in got], [("7001", target, "")], body)
        # even with an address in it, it asks no one
        stream = [c(7003, 377, at(9, "10:00"), "@codex review\n\nTo Claude: and look at the cache key too")]
        self.assertEqual(asks.read(stream, {377}, at(7, "00:00"), job_threads={377}, who=who), [])


