class Answers(unittest.TestCase):
    def one(self, ask_body, *replies, n=500, job=True, target="Claude"):
        """Is the ask (comment 7001 on thread n) still open after these (thread, body) replies?"""
        stream = [c(7001, n, at(9, "10:00"), ask_body)]
        for i, (thread, body, *login) in enumerate(replies):
            stream.append(c(7010 + i, thread, at(9, f"10:{10 + i:02d}"), body, *login))
        got = asks.read(stream, {n, 340, 501}, at(7, "00:00"), job_threads={500, 501} if job else set(), who=who,
                        oid=lambda cm, t: L.ob_id("J-500" if job else "", "ask", who(t), cm["id"]))
        return [(a["id"], a["target"], a["answer"]) for a in got if a["id"] == "7001" and a["target"] == target]

    MUSE = "**Muse (via email bridge): To Claude: rule on the grip cap**\n\nTo Claude: 3800 N or 2600 N?"

    def test_on_a_jobs_own_thread_the_addressees_next_post_to_no_one_else_answers(self):
        plain = (500, "Claude (integrator): the grip cap stays at 3800 N." + FOOT)
        self.assertEqual(self.one(self.MUSE, plain), [("7001", "Claude", "reply on its thread")])
        # a post to someone else there is not the answer; the next plain one is
        to_grok = (500, "Claude (integrator): To Grok, check the grip math." + FOOT)
        self.assertEqual(self.one(self.MUSE, to_grok), [("7001", "Claude", "")])
        self.assertEqual(self.one(self.MUSE, to_grok, plain)[0][2], "reply on its thread")
        # someone else's post, a post on another job's thread, and the switchboard's own posts are no answer
        self.assertEqual(self.one(self.MUSE, (500, "Grok: drive-by note"))[0][2], "")
        self.assertEqual(self.one(self.MUSE, (501, plain[1]))[0][2], "")
        self.assertEqual(self.one(self.MUSE, (500, "Claude (integrator): PIPE ALARM: the bridge looks down.", BOT))[0][2], "")
