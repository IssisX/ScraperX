#!/usr/bin/env python3
"""Compare the Matron affordance scan with the hand-written route inventory.

The inventory is an exam key only: nothing here feeds the runtime.  Usage:
  CLIMB_SCAN_OUT=scan.json SCRAPERX_ONLY=matron-climb-scan scraperx_sim_tests
  climb_inventory_diff.py scan.json inventory.json > CLIMB_CAPABILITIES_REPORT.md
Edges are matched on the support heights of their two ends (within TOL), their
direction, and, where the inventory names places, the scanner line's distance to
one of them (XZ_TOL). Each scanner edge answers at most one inventory edge.
"""
import collections
import json
import math
import re
import sys

TOL = 0.2
XZ_TOL = 6.0


def main() -> int:
    scan = json.load(open(sys.argv[1]))
    inv = json.load(open(sys.argv[2]))
    tops = {r["id"]: r["top"] for r in scan["regions"]}
    inv_tops = {r["id"]: r.get("support_top_m") for r in inv["records"] if r["type"] == "region"}
    coord = re.compile(r"\((-?\d+(?:\.\d+)?),\s*(-?\d+(?:\.\d+)?)\)")

    def places(r):
        """(x, z) points the inventory record names in its facts, if any."""
        return [(float(x), float(z)) for x, z in coord.findall(json.dumps(r.get("facts", {})))]

    def cost(e, a, b, pts):
        """How far a scanner edge is from an inventory edge; None when it is not the same edge.
        Heights of both ends within TOL, the same direction (up stays up), and, when the
        inventory names places, the scanner's line within XZ_TOL of one of them."""
        fa, fb = tops[e["from"]], tops[e["to"]]
        if abs(fa - a) > TOL or abs(fb - b) > TOL:
            return None
        if (b - a) * (fb - fa) < 0.0 and abs(b - a) > TOL:
            return None
        c = abs(fa - a) + abs(fb - b)
        if pts:
            lx, lz = e["line"]
            d = min(math.hypot(lx - x, lz - z) for x, z in pts)
            if d > XZ_TOL:
                return None
            c += d * 0.01
        return c

    # Each scanner edge answers at most one inventory edge: the closest one.
    edges = [r for r in inv["records"] if r["type"] == "edge"]
    claims = {}
    for i, r in enumerate(edges):
        a, b = inv_tops.get(r["from"]), inv_tops.get(r["to"])
        if a is None or b is None:
            continue
        pts = places(r)
        for k, e in enumerate(scan["edges"]):
            c = cost(e, a, b, pts)
            if c is not None and (k not in claims or c < claims[k][0]):
                claims[k] = (c, i)
    per_inv = collections.defaultdict(list)
    for k, (_, i) in claims.items():
        per_inv[i].append(scan["edges"][k])

    rows, tally, matched = [], collections.Counter(), set()
    for i, r in enumerate(edges):
        a, b = inv_tops.get(r["from"]), inv_tops.get(r["to"])
        status = r.get("status") or "-"
        if a is None or b is None:
            verdict = "no height in inventory"
        else:
            es = per_inv.get(i, [])
            matched.update(id(e) for e in es)
            usable = [e for e in es if e["usable"]]
            if usable:
                verdict = "scanner: usable (" + ", ".join(sorted({e["kind"] for e in usable})) + ")"
            elif es:
                verdict = "scanner: found, rejected (" + es[0]["reason"][:70] + ")"
            else:
                verdict = "scanner: none"
        tally[(status, verdict.split(" (")[0])] += 1
        rows.append((r["id"], status, verdict))
    st = scan["stats"]
    print("# Matron climb capabilities: scanner vs inventory\n")
    print("Generated by `tools/matron/climb_inventory_diff.py`. The inventory is a held-out exam key, not")
    print("runtime input. Matching is by end heights (±%.1f m), direction and, where the inventory names" % TOL)
    print("places, position; each scanner edge counts once. Read rows against the E2E exams.\n")
    print("Scan: %d bodies, %d patches, %d ladders, %d poles, %d regions, %d edges (%d usable), %.2f s.\n" % (
        st["bodies"], st["patches"], st["ladders"], st["poles"], st["regions"], st["edges"], st["usable_edges"], st["seconds"]))
    print("## Tally\n\n| inventory | scanner | count |\n|---|---|---|")
    for (s, v), n in sorted(tally.items()):
        print("| %s | %s | %d |" % (s, v, n))
    print("\n## Edges\n\n| inventory edge | inventory status | scanner |\n|---|---|---|")
    for row in rows:
        print("| %s | %s | %s |" % row)
    extra = [e for e in scan["edges"] if e["usable"] and id(e) not in matched]
    print("\n## Usable scanner edges with no inventory pair: %d\n" % len(extra))
    for kind, n in sorted(collections.Counter(e["kind"] for e in extra).items()):
        print("- %s: %d" % (kind, n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
