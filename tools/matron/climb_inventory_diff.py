#!/usr/bin/env python3
"""Compare the Matron affordance scan with the hand-written route inventory.

The inventory is an exam key only: nothing here feeds the runtime.  Usage:
  CLIMB_SCAN_OUT=scan.json SCRAPERX_ONLY=matron-climb-scan scraperx_sim_tests
  climb_inventory_diff.py scan.json inventory.json > CLIMB_CAPABILITIES_REPORT.md
Edges are matched on the support heights of their two ends (within TOL).
"""
import collections
import json
import sys

TOL = 0.2


def main() -> int:
    scan = json.load(open(sys.argv[1]))
    inv = json.load(open(sys.argv[2]))
    tops = {r["id"]: r["top"] for r in scan["regions"]}
    inv_tops = {r["id"]: r.get("support_top_m") for r in inv["records"] if r["type"] == "region"}
    by_pair = collections.defaultdict(list)
    for e in scan["edges"]:
        by_pair[(round(tops[e["from"]], 1), round(tops[e["to"]], 1))].append(e)

    def found(a, b):
        return [e for (fa, fb), es in by_pair.items() if abs(fa - a) <= TOL and abs(fb - b) <= TOL for e in es]

    rows, tally, matched = [], collections.Counter(), set()
    for r in inv["records"]:
        if r["type"] != "edge":
            continue
        a, b = inv_tops.get(r["from"]), inv_tops.get(r["to"])
        status = r.get("status") or "-"
        if a is None or b is None:
            verdict = "no height in inventory"
        else:
            es = found(a, b)
            matched.update(id(e) for e in es)
            usable = [e for e in es if e["usable"]]
            if usable:
                verdict = "scanner: usable (" + ", ".join(sorted({e["kind"] for e in usable})) + ")"
            elif es:
                verdict = "scanner: found, rejected (" + es[0]["reason"][:70] + ")"
            else:
                verdict = "scanner: none"
        tally[(status, verdict.split(" (")[0])] += 1
        rows.append((r["id"], status, verdict))
    st = scan["stats"]
    print("# Matron climb capabilities: scanner vs inventory\n")
    print("Generated by `tools/matron/climb_inventory_diff.py`. The inventory is a held-out exam key, not")
    print("runtime input. Matching is by end heights only (±%.1f m), so a match means the scanner found *a*" % TOL)
    print("way between those heights, not necessarily the inventory's; read rows against the E2E exams.\n")
    print("Scan: %d bodies, %d patches, %d ladders, %d poles, %d regions, %d edges (%d usable), %.2f s.\n" % (
        st["bodies"], st["patches"], st["ladders"], st["poles"], st["regions"], st["edges"], st["usable_edges"], st["seconds"]))
    print("## Tally\n\n| inventory | scanner | count |\n|---|---|---|")
    for (s, v), n in sorted(tally.items()):
        print("| %s | %s | %d |" % (s, v, n))
    print("\n## Edges\n\n| inventory edge | inventory status | scanner |\n|---|---|---|")
    for row in rows:
        print("| %s | %s | %s |" % row)
    extra = [e for e in scan["edges"] if e["usable"] and id(e) not in matched]
    print("\n## Usable scanner edges with no inventory pair: %d\n" % len(extra))
    for kind, n in sorted(collections.Counter(e["kind"] for e in extra).items()):
        print("- %s: %d" % (kind, n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
