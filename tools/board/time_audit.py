#!/usr/bin/env python3
"""Count the clock times Claude typed today, so Cory sees whether the clock rule holds (Cory 11-11).

The rule (CLAUDE.md, 11-11): Claude types no clock time in a post, a mail or a reply to Cory. The time of
a message is the timestamp GitHub or Gmail puts on it; any other moment is named by its link. This tool
does not trust that: it reads what was actually sent and lists every clock time in it.

  GitHub: today's issue and PR comments (Central day) that Claude wrote (a body with "Claude (integrator)"
          or the "Generated by [Claude Code]" footer), read through the REST API.
  Mail:   lines on stdin, one per sent mail: `<RFC 3339 send time><TAB><subject and body text>` (the
          integrator pastes them from its Gmail search; this tool cannot read Gmail).

Every clock time found is a TYPED line, with the message's own send time in Central beside it and the
minutes between them. TYPED 0 is the rule holding. Reads only.

Usage: python3 tools/board/time_audit.py [--mail-stdin] [--date YYYY-MM-DD] [--since RFC3339]
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, time, timedelta, timezone
from zoneinfo import ZoneInfo

REPO = "IssisX/ScraperX"
CENTRAL = ZoneInfo("America/Chicago")
TIME = re.compile(r"\b(1[0-2]|0?[1-9])(?::([0-5]\d))?\s*([AaPp])\.?\s*[Mm]\b")
CLAUDE_MARKS = ("Claude (integrator)", "Generated by [Claude Code]")
MAX_PAGES = 10


def to_minutes(h: str, m: str | None, ap: str) -> int:
    return (int(h) % 12 + (12 if ap.lower() == "p" else 0)) * 60 + int(m or 0)


# The bridge's own send-time lines (muse_bridge.gs): "_Mailed <date> Central._" under a Muse mail, and
# "_The mail bridge's record of a mail the integrator sent ... Central. ..._" over a copy of Claude's mail.
MACHINE_LINE = re.compile(r"^_(Mailed |The mail bridge's record of a mail ).*_$", re.M)
# The switchboard's watchdog posts (SWITCHBOARD DOWN / UP) sign as the integrator but are written by the workflow.
MACHINE_POST = ("Claude (integrator): SWITCHBOARD DOWN", "Claude (integrator): SWITCHBOARD UP")


def typed_times(text: str, sent: datetime) -> list[str]:
    if text.startswith(MACHINE_POST):   # the switchboard watchdog's own post: times read from run data, not typed
        return []
    text = MACHINE_LINE.sub("", text)
    sent_c = sent.astimezone(CENTRAL)
    sent_min = sent_c.hour * 60 + sent_c.minute
    out = []
    for t in TIME.finditer(text):
        diff = (to_minutes(*t.group(1, 2, 3)) - sent_min + 720) % 1440 - 720
        out.append(f"'{t.group(0)}' ({diff:+d} min from its send time)")
    return out


def github_comments(day: datetime) -> list[tuple[datetime, str, str]]:
    since = day.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    end = day + timedelta(days=1)
    got = []
    for page in range(1, MAX_PAGES + 1):
        res = subprocess.run(["gh", "api", f"repos/{REPO}/issues/comments?since={since}&per_page=100&page={page}"],
                             check=True, capture_output=True, text=True, timeout=60).stdout
        rows = json.loads(res)
        for c in rows:
            when = datetime.fromisoformat(c["created_at"].replace("Z", "+00:00"))
            body = c.get("body") or ""
            if when < end and any(m in body for m in CLAUDE_MARKS):
                got.append((when, c["html_url"], body))
        if len(rows) < 100:
            break
    else:
        print(f"NOTE     more than {MAX_PAGES * 100} comments since {since}: the rest not read", file=sys.stderr)
    return got


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mail-stdin", action="store_true", help="also read sent mails from stdin")
    ap.add_argument("--date", help="Central day to audit (default: today)")
    ap.add_argument("--since", help="RFC 3339 time: count only messages sent at or after it (the rule's start)")
    args = ap.parse_args()
    d = datetime.strptime(args.date, "%Y-%m-%d").date() if args.date else datetime.now(CENTRAL).date()
    day = datetime.combine(d, time(0), CENTRAL)

    since = datetime.fromisoformat(args.since.replace("Z", "+00:00")) if args.since else day
    typed = checked = 0
    for when, url, body in github_comments(day):
        if when < since:
            continue
        checked += 1
        for t in typed_times(body, when):
            typed += 1
            print(f"TYPED    post {when.astimezone(CENTRAL):%-I:%M %p} {url}: {t}")
    if args.mail_stdin:
        for line in sys.stdin:
            if not line.strip():
                continue
            stamp, _, text = line.partition("\t")
            when = datetime.fromisoformat(stamp.strip().replace("Z", "+00:00"))
            if when.astimezone(CENTRAL).date() != d or when < since:
                continue
            checked += 1
            for t in typed_times(text, when):
                typed += 1
                print(f"TYPED    mail {when.astimezone(CENTRAL):%-I:%M %p} {text[:60]!r}: {t}")
    print(f"TIME AUDIT {d}: {typed} typed clock time(s) in {checked} message(s) Claude sent")
    return 1 if typed else 0


if __name__ == "__main__":
    sys.exit(main())
